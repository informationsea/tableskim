#!/usr/bin/env python3
"""Generate src/common/cp932_table.cxx, the CP932 (Windows Shift_JIS) to
Unicode table used by text_encoding.cxx, from Python's cp932 codec.

The table is indexed by lead byte (0x81-0x9F, 0xE0-0xFC) and trail byte
(0x40-0xFC except 0x7F); 0 marks an unmapped pair. Every mapped character
is in the BMP, including the user-defined area (lead bytes 0xF0-0xF9),
which maps to the private use area as on Windows.

Usage:
  python3 tools/generate-cp932-table.py
"""

from pathlib import Path

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = [t for t in range(0x40, 0xFD) if t != 0x7F]
OUTPUT = Path(__file__).resolve().parent.parent / "src" / "common" / "cp932_table.cxx"
PER_LINE = 12


def main():
    values = []
    for lead in LEADS:
        for trail in TRAILS:
            try:
                text = bytes([lead, trail]).decode("cp932")
            except UnicodeDecodeError:
                values.append(0)
                continue
            assert len(text) == 1 and 0 < ord(text) <= 0xFFFF
            values.append(ord(text))

    lines = [
        "// Generated by tools/generate-cp932-table.py; do not edit.",
        "",
        '#include "cp932_table.hxx"',
        "",
        "const uint16_t CP932_TABLE[CP932_LEAD_COUNT * CP932_TRAIL_COUNT] = {",
    ]
    for i in range(0, len(values), PER_LINE):
        lines.append("    " + " ".join(f"0x{v:04X}," for v in values[i:i + PER_LINE]))
    lines.append("};")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT} ({sum(1 for v in values if v)} characters)")


if __name__ == "__main__":
    main()
